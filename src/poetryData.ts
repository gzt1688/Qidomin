/** 按关键词（标题 / 正文 / 说明）过滤 */
export function searchPoetry(
  kw: string,
  cat: "all" | PoetryCat
): PoetryItem[] {
  const q = kw.trim().toLowerCase();
  return POETRY.filter((it) => {
    if (cat !== "all" && it.cat !== cat) return false;
    if (!q) return true;
    const hay = [it.title, it.note ?? "", ...it.lines].join(" ").toLowerCase();
    return hay.includes(q);
  });
}

/** 随机取一首（可与当前 id 不同） */
export function randomPoetry(excludeId?: string): PoetryItem {
  if (POETRY.length === 0) {
    return { id: "empty", cat: "poem", title: "（暂无内容）", lines: [""] };
  }
  let pick = POETRY[Math.floor(Math.random() * POETRY.length)];
  if (excludeId && POETRY.length > 1) {
    let guard = 0;
    while (pick.id === excludeId && guard < 20) {
      pick = POETRY[Math.floor(Math.random() * POETRY.length)];
      guard += 1;
    }
  }
  return pick;
}
